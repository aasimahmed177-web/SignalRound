// Money a release states that is not the round's: SignSplit's $400 million "strategic seed round" was a
// financing commitment that combines capital with a package of strategic resources; Welltory's $2 million
// came from a non-dilutive financing platform; Zymofix's €6 million was the cost of its plant, financed
// partly by an undisclosed Series A; Melius's $25 million was a $5 million seed and a $20 million Series A.

import { describe, expect, test } from "vitest";
import { settleOnPage } from "../firecrawl/extract.ts";
import { moneyKindFromSentence, nonDilutiveLender } from "./money-kind.ts";
import { hostOf } from "./normalize.ts";
import { type ExtractedItem, resolveRounds } from "./resolve.ts";
import type { ExtractedRound, Stage } from "./schema.ts";

function round(p: Partial<ExtractedRound> & { company_name: string; round_type_as_written: string }): ExtractedRound {
  return {
    company_website: null,
    company_description: null,
    amount_as_written: null,
    amount_kind: "round",
    valuation_as_written: null,
    lead_investors: [],
    other_investors: [],
    announced_date: "2026-10-05",
    headquarters: null,
    sector: null,
    evidence_quote: "",
    source_url: null,
    is_background: false,
    is_rumor: false,
    ...p,
  };
}

function resolve(r: ExtractedRound, url: string, stages: Stage[] = ["pre_seed", "seed", "series_a", "series_b", "growth"]) {
  const item: ExtractedItem = { round: r, source: { url, host: hostOf(url), title: r.company_name }, page_kind: "article", grounded: true };
  return resolveRounds([item], { stages, windowStart: new Date("2026-09-01"), now: new Date("2026-10-10") });
}

const SIGNSPLIT =
  "SignSplit PBC today emerged from stealth with a $400 million strategic seed round secured with W Group, a global technology group. The financing commitment, which values SignSplit at $1 billion, combines capital with a multi-year package of strategic resources to support its global rollout.";
const WELLTORY = [
  "Welltory, a consumer health app, has secured $2 million in growth financing from longtime partner Braavo Capital to expand Welltory Care.",
  "The financing marks the latest stage in a long-term partnership.",
  "About Braavo Capital",
  "Braavo Capital is a non-dilutive financing platform for mobile app and game companies.",
].join("\n\n");
const ZYMOFIX =
  "The new facility represents a €6 million CAPEX investment, partially financed through Zymofix's equity round and partially through revenue generated by its existing customer programmes.";

