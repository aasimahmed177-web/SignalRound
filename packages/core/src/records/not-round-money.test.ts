describe("the page says what the money is beyond the round's own sentence", () => {
  test("SignSplit: the sentence after the round calls it a commitment bundled with resources, so no amount is published", () => {
    const [evidence] = SIGNSPLIT.split(/(?<=users\.|group\.) /);
    const settled = settleOnPage(
      round({
        company_name: "SignSplit",
        round_type_as_written: "strategic seed round",
        amount_as_written: "$400 million",
        other_investors: ["W Group"],
        evidence_quote: evidence,
      }),
      SIGNSPLIT,
    );
    expect(settled).toMatchObject({ money_kind: "future_commitment", money_kind_quote: SIGNSPLIT });
    const { kept } = resolve(settled, "https://www.prnewswire.com/news-releases/signsplit-secures-400-million-strategic-seed-round.html");
    expect(kept.map((r) => [r.stage, r.amount.value])).toEqual([["seed", null]]);
  });

  test("a following sentence about the round's lead or its debt is not read as the round's money", () => {
    const page =
      "Acme raised $15 million in Series A funding led by Example Ventures. The financing also includes a credit facility from a bank.";
    const settled = settleOnPage(
      round({
        company_name: "Acme",
        round_type_as_written: "Series A",
        amount_as_written: "$15 million",
        evidence_quote: page.split(". ")[0],
      }),
      page,
    );
    expect(settled.money_kind_quote ?? null).toBeNull();
  });

  test("Welltory: its only financier introduces itself as a non-dilutive financing platform, so the money is no round", () => {
    const evidence = WELLTORY.split("\n\n")[0];
    const settled = settleOnPage(
      round({
        company_name: "Welltory",
        round_type_as_written: "growth financing",
        amount_as_written: "$2 million",
        other_investors: ["Braavo Capital"],
        evidence_quote: evidence,
      }),
      WELLTORY,
    );
    expect(settled.debt_quote).toBe("Braavo Capital is a non-dilutive financing platform for mobile app and game companies.");
    const url = "https://www.prnewswire.com/news-releases/welltory-secures-additional-2-million-in-growth-financing.html";
    expect(resolve(settled, url).kept).toEqual([]);
    expect(resolve(settled, url, ["debt"]).kept.map((r) => r.stage)).toEqual(["debt"]);
  });

  test("an equity round, or a round with several investors, is not a lender's facility", () => {
    const sentences = ["Example Capital is a revenue-based financing provider for software companies."];
    expect(nonDilutiveLender("Acme raised a $10 million Series A from Example Capital.", ["Example Capital"], sentences)).toBeNull();
    expect(
      nonDilutiveLender("Acme secured $10 million from Example Capital and Other Fund.", ["Example Capital", "Other Fund"], sentences),
    ).toBeNull();
    expect(nonDilutiveLender("Acme secured $10 million from Example Capital.", ["Example Capital"], sentences)).toBe(sentences[0]);
    expect(
      nonDilutiveLender(
        "Acme secured $10 million from Example Capital.",
        ["Example Capital"],
        ["Acme, which offers revenue-based financing to merchants, works with Example Capital."],
      ),
    ).toBeNull();
  });

  test("Zymofix: a page that calls the figure the plant's cost keeps it off the Series A, whichever page reads first", () => {
    const zymofix = {
      company_name: "Zymofix",
      round_type_as_written: "Series A",
      amount_as_written: "€6 million",
      announced_date: "2026-09-30",
      lead_investors: ["First Imagine!"],
    };
    const misread = round({
      ...zymofix,
      evidence_quote:
        "Zymofix has raised €6 million in a Series A funding round to build its first industrial production facility in Deinze.",
    });
    const plant = round({
      ...zymofix,
      evidence_quote: "The €6 million facility is funded partly through a Series A round led by First Imagine!",
    });
    const item = (r: ExtractedRound, url: string): ExtractedItem => ({
      round: r,
      source: { url, host: hostOf(url), title: "Zymofix to build its first industrial plant" },
      page_kind: "article",
      grounded: true,
    });
    const items = [
      item(misread, "https://www.agrinews.example/2026/10/01/zymofix-raises-funding-for-plant"),
      item(plant, "https://www.biotechnews.example/2026/10/02/zymofix-plant-in-deinze"),
    ];
    for (const order of [items, [...items].reverse()]) {
      const { kept, dropped } = resolveRounds(order, {
        stages: ["series_a"],
        windowStart: new Date("2026-09-01"),
        now: new Date("2026-10-10"),
      });
      expect(dropped.notARound).toBe(0);
      expect(kept.map((r) => [r.stage, r.amount.value, r.lead_investors])).toEqual([["series_a", null, ["First Imagine!"]]]);
    }
    const [alone] = resolve(misread, "https://www.agrinews.example/2026/10/01/zymofix-raises-funding-for-plant", ["series_a"]).kept;
    expect(alone.amount.value).toBe(6);
  });

  test("Melius: a total split across a seed and a Series A is never taken as the Series A's amount", () => {
    const total =
      "Melius has closed a $25 million funding round, comprising a $20 million Series A led by CRV and a $5 million seed round.";
    const [melius] = resolve(
      round({
        company_name: "Melius",
        round_type_as_written: "Series A",
        amount_as_written: "$20 million",
        amount_scope: "tranche",
        lead_investors: ["CRV"],
        evidence_quote: "Melius has raised a $20 million Series A led by CRV.",
        financing_total_as_written: "$25 million",
        financing_total_quote: total,
      }),
      "https://www.globenewswire.com/news-release/2026/10/06/melius-raises.html",
    ).kept;
    expect(melius).toMatchObject({ stage: "series_a", amount: { value: 20 }, financing_total_as_written: "$25 million" });
  });
});
